import './style.css';
import {
  generateStudyPack,
  InferenceMode,
  MODE_OPTIONS,
  prepareOnDevice,
  summarizeSources,
  type SourceSummary,
} from './ai';
import { toAnkiTxt } from './anki';
import { chunkText } from './chunk';
import { toFriendlyError } from './errors';
import { firebaseStatus } from './firebase';
import { looksNonEnglish } from './lang';
import { SAMPLE_LECTURE } from './sample';
import type { StudyPack } from './types';

function $<T extends HTMLElement>(id: string): T {
  const el = document.getElementById(id);
  if (!el) throw new Error(`Missing #${id}`);
  return el as T;
}

const els = {
  configPanel: $('config-panel'),
  configMessage: $('config-message'),
  configMissing: $<HTMLUListElement>('config-missing'),
  form: $<HTMLFormElement>('study-form'),
  mode: $<HTMLSelectElement>('mode'),
  modeHelp: $('mode-help'),
  deviceStatus: $('device-status'),
  lecture: $<HTMLTextAreaElement>('lecture'),
  loadSample: $<HTMLButtonElement>('load-sample'),
  charCount: $('char-count'),
  langNote: $('lang-note'),
  generate: $<HTMLButtonElement>('generate'),
  status: $('status'),
  errorPanel: $('error-panel'),
  errorTitle: $('error-title'),
  errorDetail: $('error-detail'),
  chromeSetup: $('chrome-setup'),
  results: $('results'),
  badge: $('source-badge'),
  summary: $('summary'),
  terms: $<HTMLUListElement>('terms'),
  cardCount: $('card-count'),
  cards: $<HTMLOListElement>('cards'),
  download: $<HTMLButtonElement>('download'),
};

let currentPack: StudyPack | null = null;
let busy = false;

// ---- Firebase config status -------------------------------------------------

if (!firebaseStatus.ready) {
  els.configPanel.hidden = false;
  if ('error' in firebaseStatus) {
    els.configMessage.textContent = `Firebase failed to initialize: ${firebaseStatus.error}`;
    els.configMissing.hidden = true;
  } else {
    els.configMissing.replaceChildren(
      ...firebaseStatus.missing.map((name) => {
        const li = document.createElement('li');
        li.textContent = name;
        return li;
      }),
    );
  }
}

// ---- Mode selector ----------------------------------------------------------

for (const opt of MODE_OPTIONS) {
  els.mode.append(
    new Option(opt.label, opt.value, false, opt.value === InferenceMode.PREFER_ON_DEVICE),
  );
}

function selectedMode(): InferenceMode {
  return (MODE_OPTIONS.find((o) => o.value === els.mode.value) ?? MODE_OPTIONS[0]!).value;
}

function updateModeHelp(): void {
  const mode = selectedMode();
  els.modeHelp.textContent = MODE_OPTIONS.find((o) => o.value === mode)?.help ?? '';
}
els.mode.addEventListener('change', updateModeHelp);
updateModeHelp();

// ---- Text input -------------------------------------------------------------

function updateTextInfo(): void {
  const text = els.lecture.value;
  const chunks = text.trim() ? chunkText(text).length : 0;
  els.charCount.textContent =
    `${text.length.toLocaleString('en')} characters` +
    (chunks > 1 ? ` · will be processed in ${chunks} chunks` : '');
  els.langNote.hidden = !looksNonEnglish(text);
}
els.lecture.addEventListener('input', updateTextInfo);
els.loadSample.addEventListener('click', () => {
  els.lecture.value = SAMPLE_LECTURE;
  updateTextInfo();
  els.lecture.focus();
});
updateTextInfo();

// ---- Rendering --------------------------------------------------------------

const BADGE: Record<SourceSummary, { text: string; cls: string; title: string }> = {
  on_device: {
    text: 'On-device',
    cls: 'badge-device',
    title: 'Generated by Gemini Nano in Chrome',
  },
  in_cloud: { text: 'In-cloud', cls: 'badge-cloud', title: 'Generated by the cloud model' },
  mixed: {
    text: 'Mixed',
    cls: 'badge-mixed',
    title: 'Some chunks ran on-device, others in the cloud',
  },
  none: { text: 'Unknown', cls: '', title: '' },
};

function setStatus(text: string): void {
  els.status.textContent = text;
}

function setBusy(value: boolean): void {
  busy = value;
  els.generate.disabled = value || !firebaseStatus.ready;
  els.generate.textContent = value ? 'Generating…' : 'Generate study pack';
  els.form.setAttribute('aria-busy', String(value));
}

function hideError(): void {
  els.errorPanel.hidden = true;
}

function showError(title: string, detail: string, chromeSetup = false): void {
  els.errorTitle.textContent = title;
  els.errorDetail.textContent = detail;
  els.chromeSetup.hidden = !chromeSetup;
  els.errorPanel.hidden = false;
}

function renderResults(pack: StudyPack, source: SourceSummary): void {
  const badge = BADGE[source];
  els.badge.textContent = badge.text;
  els.badge.className = `badge ${badge.cls}`;
  els.badge.title = badge.title;

  els.summary.replaceChildren(
    ...pack.summary.split(/\n{2,}/).map((para) => {
      const p = document.createElement('p');
      p.textContent = para;
      return p;
    }),
  );

  els.terms.replaceChildren(
    ...pack.keyTerms.map((term) => {
      const li = document.createElement('li');
      li.className = 'chip';
      li.textContent = term;
      return li;
    }),
  );

  els.cardCount.textContent = `(${pack.cards.length})`;
  els.cards.replaceChildren(
    ...pack.cards.map((card) => {
      const li = document.createElement('li');
      li.className = 'card';
      const q = document.createElement('p');
      q.className = 'card-front';
      q.textContent = card.front;
      const a = document.createElement('p');
      a.className = 'card-back';
      a.textContent = card.back;
      li.append(q, a);
      return li;
    }),
  );
  els.download.disabled = pack.cards.length === 0;
  els.results.hidden = false;
}

// ---- Download ---------------------------------------------------------------

function downloadText(filename: string, content: string): void {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

els.download.addEventListener('click', () => {
  if (currentPack) downloadText('lectureloop-anki.txt', toAnkiTxt(currentPack.cards));
});

// ---- Generate ---------------------------------------------------------------

els.form.addEventListener('submit', (event) => {
  event.preventDefault();
  void onGenerate();
});

async function onGenerate(): Promise<void> {
  if (busy || !firebaseStatus.ready) return;
  const text = els.lecture.value.trim();
  if (!text) {
    showError('Nothing to study yet', 'Paste some lecture text or click "Load sample".');
    els.lecture.focus();
    return;
  }

  const { ai } = firebaseStatus;
  const mode = selectedMode();
  hideError();
  setBusy(true);

  try {
    if (mode !== InferenceMode.ONLY_IN_CLOUD) {
      // initializeDeviceModel() must run inside a user gesture; this click is it.
      const onDownload = (fraction: number): void => {
        els.deviceStatus.textContent =
          fraction >= 1
            ? 'Gemini Nano downloaded. Loading model…'
            : `Downloading Gemini Nano… ${Math.round(fraction * 100)}%`;
      };
      const ready = prepareOnDevice(ai, mode, onDownload);
      if (mode === InferenceMode.ONLY_ON_DEVICE) {
        setStatus('Preparing on-device model…');
        await ready;
        els.deviceStatus.textContent = '';
      } else {
        // Hybrid modes don't wait: the SDK uses the cloud until Nano is ready.
        ready
          .then(() => {
            if (els.deviceStatus.textContent)
              els.deviceStatus.textContent = 'Gemini Nano is ready.';
          })
          .catch((err: unknown) => console.warn('[LectureLoop] on-device warm-up failed', err));
      }
    }

    setStatus('Generating…');
    const result = await generateStudyPack(text, mode, {
      ai,
      onProgress: ({ chunk, total }) =>
        setStatus(total > 1 ? `Chunk ${chunk}/${total}…` : 'Generating…'),
    });
    currentPack = result.data;
    renderResults(result.data, summarizeSources(result.sources));
    setStatus(`Done: ${result.data.cards.length} cards.`);
  } catch (err) {
    console.error('[LectureLoop] generation failed', err);
    // In "Only on-device" a failed warm-up leaves a stale download message.
    if (mode === InferenceMode.ONLY_ON_DEVICE) els.deviceStatus.textContent = '';
    const friendly = toFriendlyError(err, mode);
    showError(friendly.title, friendly.detail, friendly.showChromeSetup);
    setStatus('');
  } finally {
    setBusy(false);
  }
}

setBusy(false);
